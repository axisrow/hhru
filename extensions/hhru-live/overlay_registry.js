// Реестр известных модалок live-канала как ДАННЫЕ (#1227, эпик «реестр как
// данные вместо разбора каждого случая»; первая миграция — попап
// подтверждения переезда #1251/#1135). До этого файла знание о каждой
// модалке жило кодом — if-веткой в evaluateClickPolicy (executor.js): новая
// модалка = правка policy-логики. Теперь якорь цели и выдаваемый контекст —
// строка таблицы ниже: НОВАЯ ИЗВЕСТНАЯ МОДАЛКА = НОВАЯ СТРОКА, executor.js
// не правится.
//
// Семантика строки (единственный потребитель — executor.evaluateClickPolicy):
// клик с ЯВНЫМ allowApply по цели с точным data-qa targetQa, чей overlay-
// предок классифицирован ambiguous, разрешается в контексте context. Всё
// остальное не меняется: dangerous-текст отказывает и с флагом (проверяется
// раньше реестра), без allowApply тот же ambiguous отказывает (#929 этап 1),
// контролы модалки без своей строки (abort «Отменить») не адресуются.
//
// Fail-closed: пустая таблица или строка без матчинга — прежний ambiguous-
// отказ; строка ничего не кликает сама — она только называет контекст уже
// явной allowApply-команды сценария. Мутации реестр не авторизует: confirm
// попапа переезда — мутация профиля (решение владельца #1132), её допускает
// только конфиг-гейт сценария (allow_relocation); Python-реестр
// (src/hhru_bot/live/modal_registry.py, RELOCATION_MODAL) называет то же
// семейство с действием unknown — симметрично.
//
// Поля строки:
//   id          — имя семейства, дословно name записи Python-реестра;
//   targetQa    — ТОЧНЫЙ data-qa кликабельной цели (battle-подтверждён);
//   context     — метка вердикта (apply_flow_*), видна потребителю в
//                 policy.context ответа исполнителя;
//   selectorKey — ключ сгенерированного CLI-селектора
//                 (selector_groups/_generated.py) с тем же data-qa:
//                 стюард-тест связывает три слоя (tests/
//                 test_overlay_registry_js.py), чтобы канал и расширение
//                 не разъехались.
//
// Граница эпика #1227: транспорт/протокол/allowlist не трогаются — таблица
// только слой данных; классификация dispositions остаётся в policy.js.
const OVERLAY_CONTEXT_RULES = [
  {
    id: 'relocation_confirm', // == RELOCATION_MODAL.name (modal_registry.py)
    // «Все равно откликнуться», боевой дамп CLI-пути 2026-09-16 (#1135),
    // 187 боевых срабатываний; census live-канала 2026-10-09 (#1251).
    targetQa: 'relocation-warning-confirm',
    // Попап монтируется ВМЕСТО формы отклика — гейт «открытая apply-модалка»
    // (панель пикера) к нему неприменим, поэтому отдельная строка, а не
    // расширение пикер-ветки.
    context: 'apply_flow_relocation_alert',
    selectorKey: 'vacancy_page.VACANCY_RELOCATION_CONFIRM',
  },
];

// Единственная механика на все строки — матч по ТОЧНОМУ data-qa цели; вместе
// с таблицей НЕ растёт. Строка без targetQa матч не даёт (fail-closed:
// пустой якорь равен отсутствию записи), каждая ветка остаётся
// заблокированной до появления точного якоря.
function findOverlayContextRule(target) {
  const qa = target.getAttribute('data-qa') || '';
  return OVERLAY_CONTEXT_RULES.find((rule) => !!rule.targetQa && rule.targetQa === qa) || null;
}
