#: Кластер по умолчанию для шаблона, чью тему оператор не назвал явно.
#: ``mixed`` намеренно НЕ входит в ``STRICT_CLUSTERS``: неизвестная тема не
#: делает вопрос комплаенс-вопросом, иначе любой пользовательский шаблон без
#: ``--cluster`` молча перестал бы отвечать.
DEFAULT_CLUSTER = "mixed"

#: Кластеры, где ответ разрешён ТОЛЬКО явным непустым static-значением (#482:
#: «Документы и комплаенс отвечаются только явным сохранённым значением»).
#: Здесь уверенная ошибка — самая дорогая: неверный ответ про гражданство или
#: судимость хуже пропущенной вакансии, поэтому ни keyword-догадка, ни LLM, ни
#: будущий ML-слот не имеют права заполнить такое поле.
STRICT_CLUSTERS: frozenset[str] = frozenset({"compliance"})

#: Признак комплаенс-вопроса ПО ТЕКСТУ, независимо от того, сопоставлен ли он с
#: каким-либо шаблоном. Кластерной проверки (``STRICT_CLUSTERS``) недостаточно:
#: она опирается на найденный шаблон, а вопрос про судимость или паспорт может
#: не совпасть ни с одним — и тогда, не будь этого паттерна, он ушёл бы в общую
#: LLM-ступень и был бы отвечён свободной генерацией. Именно там ошибка дороже
#: всего, поэтому распознавание темы не должно зависеть от успеха сопоставления.
#:
#: Список намеренно узкий и покрывает документы, правовой статус и допуски —
#: то, что нельзя ни угадать, ни сгенерировать. Ложное срабатывание безвредно
#: (вопрос уйдёт в очередь и будет решён человеком), пропуск — нет.
_COMPLIANCE_PATTERN = re.compile(
    r"паспорт|passport|снилс|инн\b|судимост|гражданств|разрешени\w*\s+на\s+работу|"
    r"вид\s+на\s+жительств|патент|воинск|военн\w*\s+билет|призыв|"
    r"медицинск\w*\s+книжк|медкнижк|справк\w*\s+о\s+несудимости|"
    r"допуск\w*\s+к\s+гостайне|секретност|"
    # Заверения «подтверждаю достоверность сведений» — юридически значимое
    # утверждение от лица кандидата, а не факт о нём: сгенерировать его
    # моделью нельзя по той же причине, что и ответ про документы.
    # Стем обрывается на «достоверн», а не «достоверност»: суффикс -ост есть
    # только у существительного, а работодатели пишут прилагательным
    # («сведения являются достоверными», «указали достоверную информацию»).
    # Живой прогон 2026-08-23: длинная форма давала 0 совпадений на корпусе из
    # 146 реальных вопросов, короткая — ровно 2, оба настоящие заверения.
    r"достоверн|"
    # «Находитесь ли вы на территории РФ» — вопрос о правовом статусе
    # пребывания, соседний с разрешением на работу и видом на жительство.
    #
    # Шире этого признак НЕ делаем. Попытка ловить резидентство по любому
    # упоминанию страны разбилась о собранные данные: в корпусе из 146 реальных
    # вопросов «проживаете в РФ» — это обычный вопрос о местоположении, на
    # который у пользователя есть готовый ответ в шаблоне ``location``
    # («Нет, Таиланд, только удалённо»). Широкий признак вместо ответа уводил
    # его в очередь и заодно блокировал вопросы про российский рынок и про
    # зарплатные ожидания для работы в РФ. Правовой статус спрашивают через
    # документы, гражданство и разрешение на работу — они выше по списку.
    r"территори\w*\s+рф|на\s+территории\s+(рф|росси)",
    re.IGNORECASE,
)

STATIC = "static"
CONTEXTUAL = "contextual"
#: Допустимые режимы шаблона. Кортеж — порядок стабилен для ``choices``.
MODES: tuple[str, ...] = (STATIC, CONTEXTUAL)


@dataclass(frozen=True)
class SeedTemplate:
    """Стартовый шаблон с признаками вопроса для keyword-стратегии.

    ``patterns`` — скомпилированные regex по УЖЕ нормализованному тексту
    (``normalize``: схлопнутые пробелы + casefold), поэтому регистр и разметка
    hh.ru на результат не влияют.

    Regex, а не список словоформ: русский вопрос склоняется («желаемая
    зарплата» / «укажите желаемую зарплату» / «зарплата?»), и фиксированные
    формы промахивались на большинстве реальных формулировок — сопоставление
    молча не срабатывало, вопрос уходил в очередь как незнакомый. Стем
    ``зарплат`` покрывает весь падежный ряд одной записью.
    """

    name: str
    cluster: str
    patterns: tuple[re.Pattern[str], ...]
    #: Контр-признаки (#490): текст помечен ТЕМОЙ шаблона, но спрашивают не о
    #: ней. Стем знает, что вопрос про зарплату, но не знает, спрашивают ли мои
    #: ожидания или мой опыт расчёта зарплат сотрудникам — а ответить суммой на
    #: второе значит отправить работодателю число вместо ответа об опыте.
    #: Пустой кортеж по умолчанию: остальные seed'ы не затронуты.
    #:
    #: Подавление, а не «снятие всего сопоставления»: если вопрос задевал ДВА
    #: шаблона, после подавления salary остаётся один хит, и вопрос, раньше
    #: уходивший в очередь, теперь отвечается («опыт расчёта зарплаты? в каком
    #: городе живёте?» -> location). Компромисс принят осознанно — на
    #: оставшуюся половину вопроса ответ действительно есть, — и закреплён
    #: тестом; tri-state, пробрасывающий неоднозначность в ``match_keyword``,
    #: не строим: оверинжиниринг под гипотетику.
    excludes: tuple[re.Pattern[str], ...] = ()

    def matches(self, normalized_text: str) -> bool:
        if any(pattern.search(normalized_text) for pattern in self.excludes):
            return False
        return any(pattern.search(normalized_text) for pattern in self.patterns)


def _seed(name: str, cluster: str, *patterns: str, excludes: tuple[str, ...] = ()) -> SeedTemplate:
    # ``excludes`` keyword-only: ``patterns`` — varargs, и позиционный аргумент
    # после них молча уехал бы в признаки шаблона.
    return SeedTemplate(
        name,
        cluster,
        tuple(re.compile(p) for p in patterns),
        tuple(re.compile(p) for p in excludes),
    )


