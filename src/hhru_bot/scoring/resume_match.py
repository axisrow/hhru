# Маркеры отрицания (#490). «не»/«без»/«нет» перед токеном и «не требуется»/
# «не нужен» после него — самые частые формулировки hh.ru для «навык не нужен».
_NEGATION_BEFORE = frozenset({"не", "без", "нет", "кроме", "исключая", "no", "without"})
_NEGATION_AFTER = frozenset({"требуется", "нужен", "нужно", "нужна", "обязателен", "обязательно"})

# Слова, отменяющие маркер отрицания сразу за ним: «не ТОЛЬКО Python, но и SQL»
# — конструкция УТВЕРДИТЕЛЬНАЯ, навык требуется. Без этой проверки частотная
# формулировка вакансий читалась бы как «Python не нужен» и гасила бы верное
# совпадение. Множество закрытое и крошечное намеренно: это не словарь
# исключений, а один устойчивый оборот русского языка.
_NEGATION_CANCELLERS = frozenset({"только", "столько"})

# Окно поиска маркера отрицания вокруг токена (в токенах). Оно применяется
# только внутри одной клаузы; границы пунктуации сохраняются отдельно при
# токенизации.
_NEGATION_WINDOW_BEFORE = 1
# Сколько слов может стоять между навыком и парой «не требуется». Пара сама
# занимает ещё два токена, поэтому фактический хвост длиннее этого числа.
_NEGATION_WORDS_BEFORE_REQUIREMENT = 3


def _tokenize(text: str) -> list[str]:
    """Токенизирует текст в нижнем регистре, отбрасывая пустое и стоп-слова.

    ``ё`` сворачивается в ``е``: hh.ru пишет одно и то же слово обоими способами
    («учёт» в резюме vs «учета» в вакансии), и без нормализации это разные
    токены — совпадение терялось молча, занижая score.

    Маркеры отрицания (``_NEGATION_BEFORE``/``_NEGATION_AFTER``) сохраняются,
    даже когда они же перечислены в стоп-словах: выброшенное «не» разрывало бы
    окно ``_is_negated`` и «Python не требуется» снова читалось бы как
    совпадение — ровно тот дефект #490, который эта функция и должна гасить.
    """
    tokens, _ = _tokenize_with_boundaries(text)
    return tokens


_CLAUSE_SEP = re.compile(r"[.!?;\n•]+", re.UNICODE)
_TOKEN = re.compile(r"\w+", re.UNICODE)


def _tokenize_with_boundaries(text: str) -> tuple[list[str], list[int]]:
    """Возвращает токены и номер клаузы для каждого токена.

    Пунктуация не попадает в токены, но её позиции сохраняются через номер
    клаузы. Клауза — это ГРАНИЦА ПРЕДЛОЖЕНИЯ (#509: точка, ``;``, перевод
    строки, bullet), а не любой знак препинания: запятая и двоеточие внутри
    одного предложения («Не требуется: Python», «Python, больше не требуется»)
    не разрывают связь маркера отрицания с навыком. Это не даёт окну отрицания
    переносить маркер через границу ПРЕДЛОЖЕНИЯ. Стоп-слова сравниваются по стему:
    например, ``опыта`` исчезает так же, как базовое ``опыт``, и обязательная
    конструкция «без опыта Python» остаётся соседней после фильтрации.
    """
    normalized = text.lower().replace("ё", "е")
    tokens: list[str] = []
    clause_ids: list[int] = []
    clause = 0
    cursor = 0
    for match in _TOKEN.finditer(normalized):
        if _CLAUSE_SEP.search(normalized[cursor : match.start()]):
            clause += 1
        token = match.group()
        if token and (
            not _is_stopword(token) or token in _NEGATION_BEFORE or token in _NEGATION_AFTER
        ):
            tokens.append(token)
            clause_ids.append(clause)
        cursor = match.end()
    return tokens, clause_ids


def _stem(token: str) -> str:
    """Сводит токен к стему, снимая одно русское окончание из ``_RU_SUFFIXES``.

    Латинские токены проходят нетронутыми без отдельной проверки алфавита: все
    ``_RU_SUFFIXES`` — кириллица, и латинское слово на них не заканчивается.
    Поэтому «java»/«javascript» и «react»/«reactive» остаются разными стемами
    сами собой (отдельная защита по алфавиту была бы мёртвым кодом — проверено
    на латинских и смешанных токенах, включая транслит вида «питона»).
    """
    for suffix in _RU_SUFFIXES:
        if token.endswith(suffix) and len(token) - len(suffix) >= _MIN_STEM_LEN:
            return token[: -len(suffix)]
    return token


_STOPWORD_STEMS = frozenset(_stem(word) for word in _STOPWORDS)


def _is_stopword(token: str) -> bool:
    """Проверяет стоп-слово с той же нормализацией, что и матчинг."""
    return token in _STOPWORDS or _stem(token) in _STOPWORD_STEMS


def _tokens_match(profile_token: str, vacancy_token: str) -> bool:
    """Матчит токен профиля с токеном вакансии по общему стему.

    Нормализация обоих токенов к стему и сравнение на РАВЕНСТВО — вместо
    сравнения по префиксу, которое здесь стояло раньше и было структурно
    неспособно решать задачу: русское словоизменение окончание ЗАМЕЩАЕТ, а не
    дописывает, поэтому ``startswith`` даёт False на «тестирование» ~
    «тестировании» независимо от длин, и никакой порог этого не лечит (на
    списке обычных словоформ префиксный матч давал 3/15, стем-нормализация даёт
    13/15).

    Симметрично по построению: сравниваются два стема, а не «кто чей префикс».

    Известное ограничение: односложные пары вида «тест» ~ «тесто» стем сводит к
    одному значению и матч ложно срабатывает. Случай редкий (нужно, чтобы навык
    из профиля совпал с чужим словом с точностью до одной финальной гласной), и
    направление ошибки то же, что у прежнего дефекта, — но, в отличие от него,
    это единичный остаток, а не системный сбой.
    """
    return _stem(profile_token) == _stem(vacancy_token)


def _is_negated(vacancy_tokens: list[str], index: int, clause_ids: list[int] | None = None) -> bool:
    """Стоит ли токен вакансии под отрицанием (#490: тема есть, намерение обратное).

    Проверяется узкое окно внутри одной клаузы: маркер отрицания стоит
    непосредственно ПЕРЕД токеном («без опыта Python» после фильтрации
    стоп-слов превращается в «без Python»), пара «маркер + требование» стоит
    ПЕРЕД токеном («не требуется: Python» — двоеточие не рвёт клаузу, это одно
    предложение), или та же пара находится ПОСЛЕ него («Python больше не
    требуется»). Границы клаузы передаются отдельно от токенов, поэтому
    пунктуация внутри предложения (запятая, двоеточие) не мешает распознать
    пару, а граница ПРЕДЛОЖЕНИЯ (#509: точка, ``;``, перевод строки, bullet)
    не даёт маркеру дотянуться до чужого токена из другого предложения.

    Маркер, за которым сразу идёт слово из ``_NEGATION_CANCELLERS``, отрицанием
    НЕ считается: «не только Python, но и SQL» — утвердительная конструкция,
    навык требуется.

    Ограничение остаётся явным: конструкции с более чем
    ``_NEGATION_WORDS_BEFORE_REQUIREMENT`` вставленными словами и неявное
    смысловое отрицание без этих маркеров keyword-матчинг не распознаёт.
    """
    start = max(0, index - _NEGATION_WINDOW_BEFORE)
    for offset, token in enumerate(vacancy_tokens[start:index], start=start):
        if clause_ids is not None and clause_ids[offset] != clause_ids[index]:
            continue
        if token not in _NEGATION_BEFORE:
            continue
        following = vacancy_tokens[offset + 1] if offset + 1 < len(vacancy_tokens) else ""
        if following in _NEGATION_CANCELLERS:
            continue
        return True

    # «Не требуется: Python» — пара отрицание+требование ПЕРЕД токеном, а не
    # одиночный маркер в узком окне: «не» и «требуется» — два разных токена,
    # а _NEGATION_WINDOW_BEFORE=1 не достаёт до «не». Ищем пару с тем же
    # ограничением на число вставленных слов, что и у пары ПОСЛЕ токена.
    head_start = max(0, index - 2 - _NEGATION_WORDS_BEFORE_REQUIREMENT)
    head = vacancy_tokens[head_start:index]
    for offset, token in enumerate(head, start=head_start):
        if token not in _NEGATION_BEFORE:
            continue
        if clause_ids is not None and clause_ids[offset] != clause_ids[index]:
            continue
        following_index = offset + 1
        if following_index >= index:
            continue
        if vacancy_tokens[following_index] not in _NEGATION_AFTER:
            continue
        if clause_ids is not None and clause_ids[following_index] != clause_ids[index]:
            continue
        return True

    # «Python больше не требуется»: ищем пару отрицание+требование с ограниченным
    # числом слов между навыком и «не». Проверяем границу клаузы для каждого
    # токена, чтобы «Python. Не требуется Django» не склеилось в одну фразу.
    tail = vacancy_tokens[index + 1 : index + 2 + _NEGATION_WORDS_BEFORE_REQUIREMENT]
    for offset, token in enumerate(tail, start=index + 1):
        if token not in _NEGATION_BEFORE:
            continue
        if clause_ids is not None and clause_ids[offset] != clause_ids[index]:
            continue
        following_index = offset + 1
        if (
            following_index < len(vacancy_tokens)
            and vacancy_tokens[following_index] in _NEGATION_AFTER
        ):
            if clause_ids is None or clause_ids[following_index] == clause_ids[index]:
                return True
    return False


def _matched_ratio(
    profile_text: str, vacancy_tokens: list[str], clause_ids: list[int] | None = None
) -> float:
    """Доля токенов профиля [0, 1], подтверждённых текстом вакансии без отрицания.

    Доля, а не абсолютное число хитов: длинный список навыков не должен
    автоматически давать более высокий score, чем короткий и точный — иначе
    фактор мерил бы объём профиля, а не соответствие.
    """
    # Маркеры отрицания сохраняются в тексте ВАКАНСИИ (нужны для _is_negated),
    # но в профиле они — служебный шум: «без опыта» в summary не является
    # навыком, который стоит искать в вакансии.
    profile_tokens = [
        t for t in _tokenize(profile_text) if t not in _NEGATION_BEFORE and t not in _NEGATION_AFTER
    ]
    if not profile_tokens or not vacancy_tokens:
        return 0.0

    matched = 0
    for p_token in profile_tokens:
        hit = False
        for index, v_token in enumerate(vacancy_tokens):
            if not _tokens_match(p_token, v_token):
                continue
            if _is_negated(vacancy_tokens, index, clause_ids):
                # Совпадение под отрицанием не засчитываем, но продолжаем искать:
                # тот же навык может упоминаться в тексте ещё раз без отрицания.
                continue
            hit = True
            break
        if hit:
            matched += 1

    return matched / len(profile_tokens)


def resume_match_score(
    card: VacancyCard,
    profile: AIProfile | None,
) -> ScoreOutcome:
    """Оценивает соответствие профиля кандидата вакансии по ключевым словам (#492).

    Чистая функция: не ходит в браузер, не зовёт LLM, не бросает исключений.
    Источник текста вакансии — ``card.vacancy_text``, который заполняется уже на
    search-шаге (``card.inner_text()`` карточки), поэтому поход на страницу
    вакансии не нужен.

    Возвращает ``ScoreOutcome`` на шкале 0-100 (``mode=RESUME_MATCH_MODE``) с
    ``breakdown`` по факторам профиля — Этап 1 использует его только для
    логирования и наблюдения за распределением, отсева здесь НЕТ.

    Вырожденные входы дают строгий ``0.0``: нет профиля, пустой профиль, пустой
    ``vacancy_text``. Пустой текст вакансии — именно ноль, а не «идеальное
    совпадение»: отсутствие данных не доказывает соответствия (fail-closed —
    общий принцип проекта, ср. ``PageStateIndeterminate``).

    Но ноль «нет данных» и ноль «честно не совпало» РАЗЛИЧАЮТСЯ в ``rationale``
    (``NO_DATA_RATIONALE``). Для Этапа 1 это принципиально: оба вида нулей
    попадают в одно значение шкалы, и без пометки распределение, по которому
    Этап 2 будет калибровать порог, оказалось бы загрязнено карточками, где
    скоринг просто нечего было считать. Отдельный ``mode``/шкала для этого не
    заводятся — ``mode`` остаётся маркером ИСТОЧНИКА скоринга (#74).
    """
    if profile is None:
        return ScoreOutcome(
            score_0_100=0.0,
            mode=RESUME_MATCH_MODE,
            rationale=NO_DATA_RATIONALE,
            breakdown={},
        )

    vacancy_tokens, clause_ids = _tokenize_with_boundaries(getattr(card, "vacancy_text", "") or "")
    if not vacancy_tokens:
        return ScoreOutcome(
            score_0_100=0.0,
            mode=RESUME_MATCH_MODE,
            rationale=NO_DATA_RATIONALE,
            breakdown={},
        )

    sources: dict[str, str] = {
        "skills": " ".join(profile.skills or []),
        "desired_role": profile.desired_role or "",
        "summary": profile.summary or "",
        "highlights": " ".join(profile.highlights or []),
    }

    breakdown: dict[str, float] = {}
    weighted_sum = 0.0
    weight_total = 0.0
    for factor, text in sources.items():
        if not text.strip():
            # Незаполненный фактор не штрафует: он выпадает и из числителя, и из
            # знаменателя, поэтому профиль из одних skills может дать 100, а не
            # четверть максимума за «пустые» summary/highlights.
            continue
        weight = _FACTOR_WEIGHTS[factor]
        ratio = _matched_ratio(text, vacancy_tokens, clause_ids)
        breakdown[factor] = round(ratio * 100.0, 2)
        weighted_sum += ratio * weight
        weight_total += weight

    if weight_total <= 0.0:
        # Профиль пуст — считать было нечего, это тоже «нет данных», а не «не совпало».
        return ScoreOutcome(
            score_0_100=0.0,
            mode=RESUME_MATCH_MODE,
            rationale=NO_DATA_RATIONALE,
            breakdown={},
        )

    score = round((weighted_sum / weight_total) * 100.0, 2)
    matched_factors = ", ".join(f"{k}={v:.0f}" for k, v in breakdown.items() if v > 0.0)
    rationale = (
        f"keyword-match по профилю: {matched_factors}" if matched_factors else "совпадений нет"
    )

    return ScoreOutcome(
        score_0_100=score,
        mode=RESUME_MATCH_MODE,
        rationale=rationale,
        breakdown=breakdown,
    )
