"""Форматтер рынка вакансий — сравнение сфер по медианной ЗП (#66, Этап 1).

Владелец файла — #66. Отдельный report-топик (конвенция CLAUDE.md: один топик на
файл) — НЕ трогает report.py (#11 stats) и report_funnel.py (#13 воронка).
Переиспользует только нижний хелпер ``report._ascii_table`` (общая ASCII-рамка).

Цель Этапа 1 (#65) — МАКСИМИЗАЦИЯ ДОХОДА: подсветить сферы с ВЫШЕ медианной
зарплатой. market_summary принимает строки из History.market_salary_by_query
и рендерит ASCII-таблицу. Только текст/ASCII — НИКАКИХ эмодзи (правило проекта).
"""

from __future__ import annotations

from .report import _ascii_table


def _format_amount(amount: int) -> str:
    """Читаемая сумма: тысячи с разделителем разрядов. 0 → «—» (нет данных).

    0 как медиана означает «ни у одной вакансии сферы не указана зарплата» —
    выводить «0» как оценку дохода вводит в заблуждение, поэтому заменяем на
    прочерк. Реальные суммы форматируются с пробелом-разделителем разрядов.
    """
    if amount <= 0:
        return "—"
    return f"{amount:,}".replace(",", " ")


def _format_median(amount: int, n: int, estimated: bool = False) -> str:
    """Сумма с числом значений, по которым она посчитана: «250 000 (n=31)».

    ``n`` рядом с КАЖДОЙ цифрой, а не одной колонкой на строку: медианы «от» и
    «до» считаются по РАЗНЫМ выборкам (#125), и общий счётчик «С ЗП» не говорит,
    насколько надёжна конкретная из двух. На прогоне #67 именно незаметный
    маленький n сделал строку на двух вакансиях «лидером рынка».

    Нет данных (0) → «—» без n: писать «— (n=0)» — шум.
    """
    text = _format_amount(amount)
    if text == "—":
        return text
    if estimated:
        # ~ — ASCII-тильда, пометка эвристической оценки (НЕ эмодзи).
        text = f"~{text}"
    return f"{text} (n={n})"


def market_summary(rows: list[dict]) -> str:
    """Отрисовать сравнение сфер по медианной зарплате (ASCII-таблица).

    ``rows`` — вывод ``History.market_salary_by_query`` (уже отсортирован
    выгодным-наверху с учётом размера выборки, summary НЕ пересортирует —
    ответственность слоя данных). Колонки: Сфера / Медиана «от» / Медиана «до» /
    Валюта / Вакансий / С ЗП.

    #125: медиан ДВЕ — по нижней границе вилки и по верхней, каждая со своим
    ``n`` прямо в ячейке. Одна колонка «Медиана» показывала только верхние
    границы, а вакансии «от N» не участвовали в расчёте вообще. Две цифры дают
    коридор («от 150 000 до 250 000»), который сам по себе информативнее одной.

    ``low_sample``: сфера, где реальных ЗП меньше порога, помечается ``!`` перед
    названием и уходит вниз таблицы (порядок задаёт слой данных). Сноска
    расшифровывает маркер — иначе ``!`` читается как «важное», а не как
    «не доверяй цифре».

    ``estimated`` (#93): сфера, в медиану которой вошли эвристические оценки ЗП
    вакансий без указанной — помечается ``~`` перед суммой (derived-view, честно
    отличать реальную медиану от оценки). Оценка строится на верхней границе,
    поэтому ``~`` появляется только у медианы «до» (#125). ``~`` и ``!`` — НЕ
    эмодзи, ASCII; правило «без эмодзи» соблюдено.

    Пустой список → строка «Нет данных о рынке. Запустите ``search``, чтобы
    собрать вакансии.» (подсказка, что рынок пуст, пока search не записал).
    """
    if not rows:
        return "Нет данных о рынке. Запустите search, чтобы собрать вакансии."

    header = ["Сфера", 'Медиана "от"', 'Медиана "до"', "Валюта", "Вакансий", "С ЗП"]
    body: list[list[str]] = []
    other_currency_total = 0
    low_sample_total = 0
    for r in rows:
        # Оценки (#93) достраивают только верхнюю границу — тильда лишь у неё.
        median_from = _format_median(int(r.get("median_from", 0) or 0), int(r.get("with_from", 0)))
        median_to = _format_median(
            int(r.get("median_to", 0) or 0),
            int(r.get("with_to", 0)),
            estimated=bool(r.get("estimated")),
        )
        # #122: сколько вакансий сферы имеют ЗП в другой валюте — они НЕ в медиане.
        other = int(r.get("other_currency", 0) or 0)
        other_currency_total += other
        with_salary = str(r.get("with_salary", 0))
        if other:
            with_salary = f"{with_salary} (+{other} др. вал.)"
        query = str(r.get("search_query", ""))
        if r.get("low_sample"):
            low_sample_total += 1
            query = f"! {query}"
        body.append(
            [
                query,
                median_from,
                median_to,
                str(r.get("currency") or "—"),
                str(r.get("count", 0)),
                with_salary,
            ]
        )
    table = _ascii_table(header, body)
    if low_sample_total:
        table += (
            "\n[INFO] ! — мало данных о зарплате, медиана ненадёжна; "
            "такие сферы показаны в конце списка."
        )
    if other_currency_total:
        # Сноска, а не молчание: медиана считается по доминирующей валюте сферы
        # (#122), и пользователь должен видеть, что часть данных осталась вне неё.
        table += (
            f"\n[INFO] {other_currency_total} вакансий с ЗП в другой валюте не вошли "
            "в медиану (курсы не нормализуются)."
        )
    return table
