"""Форматтер рынка вакансий — сравнение сфер по медианной ЗП (#66, Этап 1).

Владелец файла — #66. Отдельный report-топик (конвенция CLAUDE.md: один топик на
файл) — НЕ трогает report.py (#11 stats) и report_funnel.py (#13 воронка).
Переиспользует только нижний хелпер ``report._ascii_table`` (общая ASCII-рамка).

Цель Этапа 1 (#65) — МАКСИМИЗАЦИЯ ДОХОДА: подсветить сферы с ВЫШЕ медианной
зарплатой. market_summary принимает строки из History.market_salary_by_query
и рендерит ASCII-таблицу. Только текст/ASCII — НИКАКИХ эмодзи (правило проекта).
"""

from __future__ import annotations

from .report import _ascii_table


def _format_amount(amount: int) -> str:
    """Читаемая сумма: тысячи с разделителем разрядов. 0 → «—» (нет данных).

    0 как медиана означает «ни у одной вакансии сферы не указана зарплата» —
    выводить «0» как оценку дохода вводит в заблуждение, поэтому заменяем на
    прочерк. Реальные суммы форматируются с пробелом-разделителем разрядов.
    """
    if amount <= 0:
        return "—"
    return f"{amount:,}".replace(",", " ")


def market_summary(rows: list[dict]) -> str:
    """Отрисовать сравнение сфер по медианной зарплате (ASCII-таблица).

    ``rows`` — вывод ``History.market_salary_by_query`` (уже отсортирован по
    убыванию медианы выгодным-наверху, summary НЕ пересортирует —
    ответственность слоя данных). Колонки: Сфера / Медиана (верх вилки) /
    Вакансий / С ЗП (coverage — сколько вакансий с указанной зарплатой, для
    оценки доверия к медиане; мало данных с ЗП → оценка шаткая).

    ``estimated`` (#93): сфера, в медиану которой вошли эвристические оценки
    ЗП вакансий без указанной — помечается ``~`` перед суммой (derived-view,
    честно отличать реальную медиану от оценки). Знак ``~`` — НЕ эмодзи,
    ASCII-тильда; правило «без эмодзи» соблюдено.

    Пустой список → строка «Нет данных о рынке. Запустите ``search``, чтобы
    собрать вакансии.» (подсказка, что рынок пуст, пока search не записал).
    """
    if not rows:
        return "Нет данных о рынке. Запустите search, чтобы собрать вакансии."

    header = ["Сфера", "Медиана", "Валюта", "Вакансий", "С ЗП"]
    body: list[list[str]] = []
    other_currency_total = 0
    for r in rows:
        amount = _format_amount(int(r.get("median_to", 0)))
        if r.get("estimated"):
            # ~ — ASCII-тильда, пометка эвристической оценки (НЕ эмодзи).
            amount = f"~{amount}" if amount != "—" else amount
        other_currency_total += int(r.get("other_currency", 0) or 0)
        with_salary = str(r.get("with_salary", 0))
        # #122: сколько вакансий сферы имеют ЗП в другой валюте — они НЕ в медиане.
        other = int(r.get("other_currency", 0) or 0)
        if other:
            with_salary = f"{with_salary} (+{other} др. вал.)"
        body.append(
            [
                str(r.get("search_query", "")),
                amount,
                str(r.get("currency") or "—"),
                str(r.get("count", 0)),
                with_salary,
            ]
        )
    table = _ascii_table(header, body)
    if other_currency_total:
        # Сноска, а не молчание: медиана считается по доминирующей валюте сферы
        # (#122), и пользователь должен видеть, что часть данных осталась вне неё.
        table += (
            f"\n[INFO] {other_currency_total} вакансий с ЗП в другой валюте не вошли "
            "в медиану (курсы не нормализуются)."
        )
    return table
