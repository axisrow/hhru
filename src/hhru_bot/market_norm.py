"""Фолд-ключ и канонический display для market-текстов (роли/навыки/запросы).

Сырые строки (``desired_role``, ``skill``, ``search_query``) никогда не
заменяются: фолд-ключ — производное значение для дедупликации вариантов
написания («1C»/«1С»/«1 с» — один ключ), а читаемое имя для отчётов даёт
словарь канонов с fallback'ом на самую частую сырую форму группы.

Ключ НЕ транслитерирует: «чатGPT» и «ChatGPT» — разные ключи (осознанное
решение владельца репозитория). Фолдятся только регистр, буквы-гомоглифы
кириллица→латиница и небуквенно-цифровые символы (пробелы, дефисы,
двоеточия). Таблица гомоглифов намеренно минимальна — только глифы,
визуально неотличимые от латиницы; расширение на к/м/т/в/н запрещено:
в lowercase их формы различимы, а включение превращало бы в латиницу
половину любого русского слова и мультиплицировало коллизии с настоящими
латинскими строками.
"""

from __future__ import annotations

import re
from collections import Counter

# ё→e (в латиницу, а не в кириллическую е): str.translate однократный, и ё
# обязана свернуться туда же, куда сворачивается е, иначе «ёлка» ≠ «елка».
# э→e — не гомоглиф, а вариант написания (брэнд/бренд): тот же приём, что
# ё→е; риск коллизий с латинскими словами принят (в рыночных строках
# не встречается). ♯→# — единственный не-буквенный гомоглиф: музыкальная
# диеза — зрительный двойник решётки в имени C♯, и без него C♯ сливалась
# бы с одиночной C.
HOMOGLYPHS = str.maketrans(
    {
        "а": "a",
        "е": "e",
        "о": "o",
        "р": "p",
        "с": "c",
        "у": "y",
        "х": "x",
        "ё": "e",
        "э": "e",
        "♯": "#",
    }
)

# Значимые символы имён технологий СОХРАНЯЮТСЯ в ключе: C#, C++, F# не должны
# сливаться с одиночными буквами (в живой базе сотни строк таких навыков).
# Точка в keep-set НЕ входит (v4, решение владельца): сохранять её ради
# разделения версий не нужно, а она плодила артефакты вида «оператор 1С.»
# отдельным бакетом от «Оператор 1С» (замер живой базы: 1 414 точечных
# ключей / 1 835 резюме в ролях). Следствия приняты: «Node.js» ==
# «Node JS», «.NET» == «Net», «8.3» == «83». Удаляется остальное
# не-словесное: пробелы и NBSP-семейство, дефисы, двоеточия, запятые,
# скобки, эмодзи. Подчёркивание остаётся (входит в \\w) — в рыночных
# строках не встречается.
_KEY_STRIP = re.compile(r"[^\w#+]")
# Дефис сознательно НЕ разделитель: «Продавец-консультант», «AI-тренер» —
# внутрисловные; составные роли разделяют запятая/точка с запятой/слэш/пайп/
# буллеты (замер живой базы 2026-09-11: 7950/155/3502/227/11 вхождений).
# \s в str-паттернах уже покрывает NBSP-семейство (категория Zs); \uXXXX
# дублирует его явно, чтобы класс не зависел от флагов при рефакторингах.
_ROLE_SPLIT = re.compile(r"[,;/|•·]+")
_EDGE_TRIM = re.compile(r"^[\s\u00a0\u2009\u202f\-–—*•·]+|[\s\u00a0\u2009\u202f\-–—*•·]+$")


def _fold_text(value: str) -> str:
    """Фолд без алиасов: строительный блок fold_key и словаря KEY_ALIASES."""
    return _KEY_STRIP.sub("", value.casefold().translate(HOMOGLYPHS))


# Правило категорий прав (v6): «Водительское удостоверение категории X» —
# владелец не различает X («посрать, ABS или D»), класс закрывается
# префиксом, будущие категории подхватываются сами без новых алиасов.
# Паттерн строится из фолда литерала: ключ после гомоглифов — смешанная
# раскладка, рукописный литерал не совпадёт бы ни одним символом.
_LICENSE_PREFIX = _fold_text("Водительское удостоверение")
_LICENSE_CATEGORY = _fold_text("категории")
_LICENSE_RULE = re.compile(rf"^{_LICENSE_PREFIX}{_LICENSE_CATEGORY}(.+)$")


def fold_key(value: str) -> str:
    """Дедупликационный ключ написания: регистр/раскладка/пунктуация не важны.

    casefold (прецедент external_forms/detect.normalize), затем гомоглифы,
    затем удаление пунктуации и разделителей. Символы «#» и «+» сохраняются —
    это часть имён технологий: C# не сливается с C, C++ с C# (в живой базе
    C++ — 413 навыков, C# — 361; под чистым «удалить всё не-алфанумерное»
    они схлопывались в один ключ «c»). Точка удалена по решению владельца:
    это пунктуация, а её сохранение дробило роли с точкой на конце.
    Затем правило категорий прав и KEY_ALIASES: парные канонизации,
    невыразимые правилом.
    """
    key = _LICENSE_RULE.sub(_LICENSE_PREFIX, _fold_text(value))
    return KEY_ALIASES.get(key, key)


# Парные канонизации ключей, невыразимые правилом фолда без ложных склеек:
# версии платформ и число слова — решения владельца по аудиту дубликатов
# (2026-09-12). Целый класс (раскладка, регистр, ё/э, символы, точка) —
# всегда правило фолда, не алиас; алиасы — для одиночных пар, пополняются
# по результатам scripts/audit_key_dupes.py. Без цепочек: цель алиаса —
# прямой ключ, не другой алиас.
KEY_ALIASES = {
    _fold_text("1С: Предприятие 7"): _fold_text("1С: Предприятие 8"),
    _fold_text("1С: Предприятие"): _fold_text("1С: Предприятие 8"),
    _fold_text("1С: Предприятие 8.3"): _fold_text("1С: Предприятие 8"),
    _fold_text("Нейросеть"): _fold_text("Нейросети"),
    _fold_text("Мерчандайзинг"): _fold_text("Мерчендайзинг"),
    _fold_text("Adobe After Effect"): _fold_text("Adobe After Effects"),
    _fold_text("Adobe Premier Pro"): _fold_text("Adobe Premiere Pro"),
    _fold_text("Материальная отвественность"): _fold_text("Материальная ответственность"),
    _fold_text("Windows 7"): _fold_text("Windows"),
}

# Семантический слой: кластеры профессий. Фолд склеивает НАПИСАНИЯ, кластер —
# СИНОНИМЫ (QA Engineer == Тестировщик == Тестировщик ПО); агрегируем
# профессии, а не написания. Значение — читаемый id кластера (он попадает в
# role_cluster и SQL-рецепты), не fold-ключ. Только явные синонимы: граничные
# роли остаются отдельными (Главный бухгалтер ≠ Бухгалтер, помощник
# бухгалтера ≠ Бухгалтер, Маркетолог-аналитик ≠ Маркетолог — стражи в
# тестах). Пополняется вручную по аудит-топу.
ROLE_CLUSTERS = {
    _fold_text("Тестировщик"): "тестировщик",
    _fold_text("Тестировщик ПО"): "тестировщик",
    _fold_text("QA Engineer"): "тестировщик",
    _fold_text("Тестировщик игр"): "тестировщик",
    _fold_text("Тестер"): "тестировщик",
    _fold_text("Data Scientist"): "datascientist",
    _fold_text("DS"): "datascientist",
    _fold_text("Маркетолог"): "маркетолог",
    _fold_text("Интернет-маркетолог"): "маркетолог",
    _fold_text("Менеджер по маркетингу"): "маркетолог",
    _fold_text("Менеджер по маркетингу и рекламе"): "маркетолог",
}


def resolve_cluster(key: str) -> str:
    """Ключ профессии-кластера для роли; без кластера — сам ключ."""
    return ROLE_CLUSTERS.get(key, key)


def split_roles(desired_role: str) -> list[str]:
    """Разбирает составную желаемую должность на части («Оператор 1C, кладовщик»).

    Часть выживает, если её фолд-ключ не короче двух символов: эмодзи-only
    фрагменты и одиночные буквы («C», «B») — мусор разметки; символные
    языки проходят, их ключи длиннее («C++» → «c++», «C#» → «c#»).
    «1С» (ключ «1c») — роль. Первая выжившая часть — primary
    (см. competitor_resume_roles.is_primary).
    """
    trimmed = (_EDGE_TRIM.sub("", part) for part in _ROLE_SPLIT.split(desired_role))
    return [part for part in trimmed if len(fold_key(part)) >= 2]


def canonical_display(group_key: str, raw_forms: Counter[str]) -> str:
    """Читаемое имя группы фолд-ключей: словарь → топ-форма → ничья по алфавиту.

    Ничья разрешается лексикографически меньшей формой — полная
    детерминированность отчёта при равных счётчиках.
    """
    canonical = CANONICAL_DISPLAY.get(group_key)
    if canonical:
        return canonical
    top = max(raw_forms.values())
    return min(form for form, count in raw_forms.items() if count == top)


# Стартовый набор канонических имён (топы живой базы на 2026-09-11). Ключи
# строятся самой fold_key, а не литеральными строками: после фолда часть букв
# кириллицы становится латиницей («1С» → «1c»), и рукописный ключ неизбежно
# ошибался бы. Словарь влияет ТОЛЬКО на display, никогда на счётчики;
# пополнение не требует миграций — display вычисляется при чтении. Display
# должны оставаться уникальными (страж — test_canonical_display_values_are_unique):
# совпавшие слились бы в один бакет отчёта.
CANONICAL_DISPLAY = {
    fold_key(name): name
    for name in (
        "1С",
        "Оператор 1С",
        "Программист 1С",
        "Аналитик 1С",
        "Бухгалтер 1С",
        "Тестировщик ПО",
        "QA Engineer",
        "Data Scientist",
        "ChatGPT",
        "GPT",
        "1С: Предприятие 8",
        "1С: Документооборот",
        "1С: Бухгалтерия",
        "промпт-инженер",
        "MS Excel",
        "Adobe After Effects",
        "Adobe Premiere Pro",
        "Материальная ответственность",
        "Windows",
    )
} | {
    # Имена кластеров профессий: id кластера — читаемый литерал (не fold-ключ),
    # display закреплён, а не отдан на усмотрение самой частой формы.
    "тестировщик": "Тестировщик",
    "маркетолог": "Маркетолог",
    "datascientist": "Data Scientist",
}
